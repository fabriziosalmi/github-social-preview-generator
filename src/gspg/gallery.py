def _card(preview: Preview, image: str, entry: Dict[str, object]) -> str:
    # Repository facts live here rather than on the image: at feed size they
    # would be unreadable, but on a web page they are useful.
    tags = list(preview.facts)
    return """      <figure>
        <img src="%s" alt="Social preview for %s" width="1280" height="640" loading="lazy">
        <figcaption>
          <a href="https://github.com/%s">%s</a>
          <div class="sub">%s</div>
          <div class="tags">%s</div>
        </figcaption>
      </figure>""" % (
        html.escape(image),
        html.escape(preview.repo),
        html.escape(preview.repo),
        html.escape(preview.repo),
        html.escape(preview.description),
        "".join("<span>%s</span>" % (html.escape(str(tag)),) for tag in tags),
    )


def render_page(
    previews: List[Preview], lock: Dict[str, Dict[str, object]], raw_base: str
) -> str:
    cards = [
        _card(preview, "previews/%s.png" % (preview.slug,), lock.get(preview.repo, {}))
        for preview in previews
    ]
    raw_hint = (
        "<p>Every image is also addressable directly, without this page: "
        "<code>%s&lt;owner&gt;__&lt;name&gt;.png</code></p>" % (html.escape(raw_base),)
        if raw_base else ""
    )
    return """<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta http-equiv="Content-Security-Policy" content="%s">
    <meta name="referrer" content="no-referrer">
    <meta name="robots" content="index, follow">
    <meta name="description" content="Generated social preview images for %d repositories.">
    <title>Social previews</title>
    <link rel="stylesheet" href="styles.css">
  </head>
  <body>
    <main>
      <h1>Social previews</h1>
      <p class="lede">Generated offline and served from this repository. Each image is a
      deterministic function of its manifest entry, so the same input always produces the
      same file.</p>
      <p class="meta">%d previews &middot; built with gspg %s &middot; no scripts, no web fonts,
      no third-party requests</p>
      <div class="grid">
%s
      </div>
      <footer>
        <p>To use one: download it and upload it under
        <code>Settings &rarr; Social preview</code> on the repository. GitHub offers no
        API for this, so it is the one manual step.</p>
        %s
      </footer>
    </main>
  </body>
</html>
""" % (CSP, len(previews), len(previews), __version__, "\n".join(cards), raw_hint)


def render_index(
    previews: List[Preview], lock: Dict[str, Dict[str, object]], raw_base: str
) -> str:
    """A machine-readable index, for anything that wants the URLs in bulk."""
    payload = {
        "generator": "gspg %s" % (__version__,),
        "count": len(previews),
        "previews": [
            {
                "repo": preview.repo,
                "file": "previews/%s.png" % (preview.slug,),
                "raw_url": (raw_base + preview.slug + ".png") if raw_base else None,
                "pattern": lock.get(preview.repo, {}).get("pattern"),
                "accent": lock.get(preview.repo, {}).get("accent"),
            }
            for preview in previews
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def build(
    manifest: Manifest,
    lock: Dict[str, Dict[str, object]],
    output_dir: str,
    site_dir: str,
    raw_base: str = "",
) -> Tuple[List[str], List[str]]:
    """Assemble the site into ``site_dir``. Returns (written paths, warnings)."""
    previews = manifest.active()
    png_dir = os.path.join(output_dir, "png")
    site_images = os.path.join(site_dir, "previews")
    os.makedirs(site_images, exist_ok=True)

    warnings: List[str] = []
    included: List[Preview] = []
    for preview in previews:
        source = os.path.join(png_dir, preview.slug + ".png")
        if not os.path.exists(source):
            warnings.append(
                "%s: no rendered PNG, left out of the gallery" % (preview.repo,)
            )
            continue
        shutil.copyfile(source, os.path.join(site_images, preview.slug + ".png"))
        included.append(preview)

    if not included:
        raise RenderError(
            "no rendered previews found in %s. Run `gspg build` first." % (png_dir,)
        )

    # Anything left from a previous build for a repository no longer listed.
    keep = {preview.slug + ".png" for preview in included}
    for name in sorted(os.listdir(site_images)):
        if name.endswith(".png") and name not in keep:
            os.remove(os.path.join(site_images, name))

    written: List[str] = []
    for name, content in (
        ("index.html", render_page(included, lock, raw_base)),
        ("styles.css", STYLESHEET),
        ("index.json", render_index(included, lock, raw_base)),
        # Without this, Pages hides any path beginning with an underscore.
        (".nojekyll", ""),
    ):
        path = os.path.join(site_dir, name)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
        written.append(path)
    written.append(site_images)
    return written, warnings
