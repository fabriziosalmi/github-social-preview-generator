"""The public gallery: a self-contained static site listing every preview.

This is the "public storage" half of the project, and it is deliberately built
to the same standard as the images themselves.

The assembled site talks to nothing but its own origin. No CDN, no web font,
no analytics, no script of any kind; the stylesheet is a same-origin file
rather than an inline block, so the page's own Content-Security-Policy can
refuse ``unsafe-inline`` instead of tolerating it. The result satisfies the
egress, CSP and privacy families of AGSSH-STD-001 as a static surface, and can
be checked with ``agssh`` once deployed.

Images are copied into the site at assembly time rather than committed twice,
so the repository keeps exactly one copy of every PNG.
"""

from __future__ import annotations

import html
import json
import os
import shutil
from typing import Dict, List, Tuple

from . import __version__
from .config import Manifest
from .errors import RenderError
from .model import Preview

#: Locks the page to its own origin. Expressed as a meta element because
#: GitHub Pages does not let a repository set response headers; a real
#: deployment behind a proxy should send the same policy as a header, which is
#: the stronger assurance tier.
CSP = (
    "default-src 'none'; "
    "img-src 'self'; "
    "style-src 'self'; "
    "base-uri 'none'; "
    "form-action 'none'; "
    "frame-ancestors 'none'"
)

